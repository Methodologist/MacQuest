"""
Build per-zone walkability grids for the terrain-aware arrow -> SpeedLevel/Data/Terrain.lua

WoW gives addons no terrain data, so walkability is inferred:
  '='  road:     cells on NPC patrol paths (QuestieDB waypoints) or cells players actually walked
                 (SavedVariables walkData from the addon, merged in when present)
  'o'  walkable: cells holding NPC / object spawns, grown by one cell to bridge small gaps
  '.'  unknown:  no evidence at all - typically mountains, deep water, cliffs, map edges

The in-game A* treats unknown cells as expensive (not forbidden) and roads as cheap.
Grids are GRID x GRID cells over each zone map, run-length encoded.
"""
import re
from collections import defaultdict
from pathlib import Path

GRID = 96


def cell_of(x, y):
    cx = min(GRID - 1, max(0, int(x / 100 * GRID)))
    cy = min(GRID - 1, max(0, int(y / 100 * GRID)))
    return cx, cy


def raster(a, b):
    """cells along a segment (map %)"""
    (x0, y0), (x1, y1) = cell_of(*a), cell_of(*b)
    n = max(abs(x1 - x0), abs(y1 - y0), 1)
    for i in range(n + 1):
        yield round(x0 + (x1 - x0) * i / n), round(y0 + (y1 - y0) * i / n)


def rle(rows):
    flat = "".join("".join(r) for r in rows)
    out = []
    i = 0
    while i < len(flat):
        j = i
        while j < len(flat) and flat[j] == flat[i]:
            j += 1
        out.append(f"{flat[i]}{j - i}")
        i = j
    return "".join(out)


def build(br, maps, walk_data=None, out_path=None):
    """br = build_route module (for N, O, spawns_of, A2U); maps = uiMap ids to build"""
    maps = set(maps)
    evid = defaultdict(set)
    road = defaultdict(set)
    for kind, table in (("npc", br.N), ("obj", br.O)):
        for eid in table:
            for m, pts in br.spawns_of(kind, eid).items():
                if m in maps:
                    for p in pts:
                        evid[m].add(cell_of(*p))
    # patrol paths -> roads
    for nid, e in br.N.items():
        paths = e.get("paths")
        if not isinstance(paths, dict):
            continue
        for z, lines in paths.items():
            m = br.A2U.get(int(z))
            if m not in maps:
                continue
            for line in lines or []:
                pts = [tuple(p[:2]) for p in (line or []) if p and len(p) >= 2 and p[0] is not None and p[0] >= 0]
                for a, b in zip(pts, pts[1:]):
                    for c in raster(a, b):
                        road[m].add(c)
    # cells players walked (from the addon's SavedVariables)
    walked = 0
    for m, cells in (walk_data or {}).items():
        try:
            m = int(m)
        except (TypeError, ValueError):
            continue
        if m not in maps:
            continue
        for idx in (cells if isinstance(cells, (list, set)) else cells.keys()):
            try:
                idx = int(idx) - 1  # Lua 1-based
            except (TypeError, ValueError):
                continue
            road[m].add((idx % GRID, idx // GRID))
            walked += 1

    lines = ["-- GENERATED by tools/terrain.py (QuestieDB spawns + patrol paths + walked cells). Do not edit.",
             "local _, SL = ...",
             f"SL.TerrainGrid = {GRID}",
             "-- '=' road (patrol path / walked)  'o' walkable (spawns)  '.' unknown;  run-length encoded rows",
             "SL.Terrain = {"]
    stats = []
    for m in sorted(maps):
        if not evid[m] and not road[m]:
            continue
        grid = [["."] * GRID for _ in range(GRID)]
        for (x, y) in evid[m]:
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    xx, yy = x + dx, y + dy
                    if 0 <= xx < GRID and 0 <= yy < GRID:
                        grid[yy][xx] = "o"
        for (x, y) in road[m]:
            grid[y][x] = "="
        known = sum(1 for r in grid for c in r if c != ".")
        stats.append((m, known))
        lines.append(f'[{m}]="{rle(grid)}",')
    lines.append("}")
    if out_path:
        Path(out_path).write_text("\n".join(lines) + "\n", encoding="utf-8")
    return stats, walked
